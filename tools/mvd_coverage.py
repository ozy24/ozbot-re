#!/usr/bin/env python3
"""
Human-vs-bot coverage from the ladder MVDs: where do real duellists stand that
the bot's nav graph never reaches?

For each map with ladder demos (demos/mvd/) and a nav (baselines/nav_shipped/,
else baselines/nav_pool/), every grounded, alive 40Hz duellist sample is
matched to its nearest nav node.  Samples farther than --radius from any node
are human-only territory; they are clustered on a 128u grid and ranked by human
time.  Each cluster is a candidate missing link, ledge or playbook site --
cross-check against GATED.md (unreachable items) before recording anything.

Usage:
    py tools/mvd_coverage.py [--radius 128] [--top 5] [--out COVERAGE.md]
"""

import argparse
import collections
import glob
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import mvd2parse
import nav_edit
import rig_platform

MVD = os.path.join(REPO, "demos", "mvd")
CELL = 128.0


def nav_for(m):
    f = rig_platform.map_file(m)
    for d in ("nav_shipped", "nav_pool"):
        p = os.path.join(REPO, "baselines", d, f"{f}.nav")
        if os.path.isfile(p):
            return p, d
    return None, None


class Grid:
    """Bucketed nearest-node lookup (nodes are a few hundred per map)."""
    def __init__(self, pts, size=256.0):
        self.size = size
        self.b = collections.defaultdict(list)
        for p in pts:
            self.b[self.key(p)].append(p)

    def key(self, p):
        return tuple(int(math.floor(c / self.size)) for c in p)

    def nearest(self, p, cap):
        k = self.key(p)
        best = cap
        r = int(math.ceil(cap / self.size))
        for dx in range(-r, r + 1):
            for dy in range(-r, r + 1):
                for dz in range(-r, r + 1):
                    for q in self.b.get((k[0] + dx, k[1] + dy, k[2] + dz), ()):
                        d = math.dist(p, q)
                        if d < best:
                            best = d
        return best


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--radius", type=float, default=128.0)
    ap.add_argument("--top", type=int, default=5)
    ap.add_argument("--out", default=os.path.join(REPO, "COVERAGE.md"))
    args = ap.parse_args()

    by_map = collections.defaultdict(list)
    with open(os.path.join(MVD, "manifest.jsonl")) as f:
        for line in f:
            r = json.loads(line)
            by_map[r["map"]].append(os.path.join(MVD, r["id"] + ".mvd2.gz"))

    L = ["# ozbot-re — where ladder humans go that the bot's nav does not", "",
         "_Generated by `tools/mvd_coverage.py` from the ladder MVDs (both duellists, 40Hz, "
         f"grounded + alive samples) against each map's pinned nav. A sample is uncovered when "
         f"no nav node is within {args.radius:.0f}u._", "",
         "| Map | demos | nav | human time | uncovered | top uncovered spots (128u cell centre, share of human time) |",
         "|---|---:|---|---:|---:|---|"]
    for m in sorted(by_map):
        navp, src = nav_for(m)
        if not navp:
            continue
        nodes, _ = nav_edit.load(navp)
        grid = Grid([n["origin"] for n in nodes])
        total = unc = 0
        cells = collections.Counter()
        for path in by_map[m]:
            try:
                d = mvd2parse.parse(path)
            except Exception:
                continue
            nf = len(d["frames"])
            for slot, lst in d["players"].items():
                if sum(1 for s in lst if s is not None and s.pm_type == mvd2parse.PM_NORMAL) < nf // 2:
                    continue
                for i in range(0, nf, 4):            # 10Hz is plenty for occupancy
                    s = lst[i]
                    if s is None or s.pm_type != mvd2parse.PM_NORMAL or s.health <= 0:
                        continue
                    if not (s.pm_flags & 4):          # PMF_ON_GROUND
                        continue
                    total += 1
                    if grid.nearest(s.origin, args.radius) >= args.radius:
                        unc += 1
                        cells[tuple(round(c / CELL) * int(CELL) for c in s.origin)] += 1
        if not total:
            continue
        top = ", ".join(f"({c[0]}, {c[1]}, {c[2]}) {100 * n / total:.1f}%"
                        for c, n in cells.most_common(args.top))
        L.append(f"| {m} | {len(by_map[m])} | {src} | {total / 10 / 60:.0f} min | "
                 f"**{100 * unc / total:.1f}%** | {top or '—'} |")
        print(f"{m}: {100 * unc / total:.1f}% of {total / 600:.0f} human-minutes uncovered", flush=True)
    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"-> {args.out}")


if __name__ == "__main__":
    main()
