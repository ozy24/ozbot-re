#!/usr/bin/env python3
"""
Per-map list of items the bot cannot route to: the to-do list for recorded
playbooks (record_inputs.bat -> make_playbook.py) or surgical nav_edit.py links.

For each map, boots one short server on the map's pinned nav (baselines/
nav_shipped, else baselines/nav_pool) and reads the load-time reachability
sweep (bot_reachlog): every item whose code is not "ok" -- no_path (the graph
has no route from a spawn) or gated:<kind> (reachable only through a lift /
train / playbook capability).  Items sitting in lava are excluded (never goals).

Usage:
    py tools/gated_items.py [--maps q2dm1,...] [--out GATED.md]
"""

import argparse
import collections
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import ab_cvar
import ladder_pool

Q2DM = [f"q2dm{i}" for i in range(1, 9)]


def reach(m, when="load", seconds=3, bots=1, instances=1):
    ab_cvar.AB_MOD = "ozbotre_gated"
    ab_cvar.stage(m)
    cmd = [sys.executable, os.path.join(HERE, "run_parallel.py"), "--repro", "--fastsim",
           "--mod", "ozbotre_gated", "--map", m, "--bots", str(bots), "--instances", str(instances),
           "--seconds", str(seconds), "--seed", "1", "--base-port", "28600",
           "--cvar", "sv_fps", "40", "--no-analyze"]
    out = subprocess.run(cmd, capture_output=True, text=True).stdout
    mt = re.search(r"-> (\S+\.jsonl)", out)
    if not mt:
        return None
    rows = []
    with open(mt.group(1)) as f:
        for line in f:
            if '"type": "reach"' in line and f'"when": "{when}"' in line:
                rows.append(json.loads(line))
    if when == "quit" and instances > 1:
        # one record per server: an item counts as ok if ANY server's matured
        # graph routes it (each worker learns independently)
        best = {}
        rank = {"ok": 3}
        for r in rows:
            k = (r["item"], round(r["x"]), round(r["y"]), round(r["z"]))
            sc = 3 if r["code"] == "ok" else (1 if r["code"] == "no_path" else 2)
            if k not in best or sc > best[k][0]:
                best[k] = (sc, r)
        rows = [v[1] for v in best.values()]
    os.remove(mt.group(1))
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--maps", default=",".join(Q2DM + [m for m in ladder_pool.POOL if m not in Q2DM]))
    ap.add_argument("--out", default=os.path.join(REPO, "GATED.md"))
    ap.add_argument("--when", choices=("load", "quit"), default="quit",
                    help="quit (default): the graph after bots played and learned for "
                         "--seconds; load: the persisted graph as shipped")
    ap.add_argument("--seconds", type=float, default=90)
    ap.add_argument("--bots", type=int, default=5)
    ap.add_argument("--instances", type=int, default=4)
    args = ap.parse_args()
    L = ["# ozbot-re — items the bot cannot route to", "",
         f"_Generated by `tools/gated_items.py` from each map's **{args.when}-time** reach sweep "
         "on its pinned nav (`baselines/nav_shipped/`, else `baselines/nav_pool/`)"
         + (f", after {args.instances} servers x {args.bots} bots x {args.seconds:.0f}s of play and learning "
            "(an item counts as reachable if any server's graph routes it)" if args.when == "quit" else "")
         + ". Judged from every deathmatch spawn._", "",
         "**no_path** = the graph has no route from a spawn — the candidates for a recorded "
         "playbook (`record_inputs.bat` → `make_playbook.py`) or a surgical `nav_edit.py` "
         "link. **gated:*kind*** = reachable only through that capability (lift/train/"
         "playbook), listed for completeness.", "",
         "| Map | items | ok | gated | no_path |", "|---|---:|---:|---:|---:|"]
    detail = []
    for m in args.maps.split(","):
        rows = reach(m, args.when, args.seconds if args.when == "quit" else 3,
                     args.bots if args.when == "quit" else 1,
                     args.instances if args.when == "quit" else 1)
        if rows is None:
            L.append(f"| {m} | — | — | — | — |")
            continue
        c = collections.Counter("ok" if r["code"] == "ok" else
                                ("no_path" if r["code"] == "no_path" else "gated") for r in rows)
        L.append(f"| {m} | {len(rows)} | {c['ok']} | {c['gated']} | {c['no_path']} |")
        bad = [r for r in rows if r["code"] != "ok"]
        if bad:
            detail.append(f"## {m}")
            detail.append("")
            detail.append("| item | position | code |")
            detail.append("|---|---|---|")
            for r in sorted(bad, key=lambda r: (r["code"], r["item"])):
                code = r["code"] + (f":{r['gate']}" if r.get("gate") else "")
                detail.append(f"| {r['item']} | ({r['x']:.0f}, {r['y']:.0f}, {r['z']:.0f}) | {code} |")
            detail.append("")
        print(f"{m}: {len(rows)} items, {c['no_path']} no_path, {c['gated']} gated", flush=True)
    import shutil
    shutil.rmtree(os.path.join(ab_cvar.ENGINE, "ozbotre_gated"), ignore_errors=True)
    with open(args.out, "w") as f:
        f.write("\n".join(L + [""] + detail) + "\n")
    print(f"-> {args.out}")


if __name__ == "__main__":
    main()
